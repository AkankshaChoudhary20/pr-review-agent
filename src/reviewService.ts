import { createOctokit, fetchPullRequestDiff, postPullRequestComment } from "./github.js";
import { reviewDiff } from "./claude.js";
import { insertReview, upsertPullRequest } from "./repository.js";
import { PullRequestWebhookPayload, ReviewResult } from "./types.js";

const SUPPORTED_ACTIONS = new Set(["opened", "synchronize"]);

/** Should this webhook delivery trigger a review? */
export function isReviewableEvent(
  eventName: string | undefined,
  payload: unknown,
): payload is PullRequestWebhookPayload {
  if (eventName !== "pull_request") return false;
  const action = (payload as { action?: unknown } | null)?.action;
  return typeof action === "string" && SUPPORTED_ACTIONS.has(action);
}

/**
 * Full pipeline for one pull_request event: fetch the diff, ask Claude to
 * review it, persist the result, and post it back as a PR comment.
 *
 * Runs in the background after the webhook handler has already acknowledged
 * the request — errors here are logged, not re-thrown to a caller.
 */
export async function processPullRequestEvent(
  payload: PullRequestWebhookPayload,
): Promise<void> {
  const { repository, pull_request: pr, action } = payload;
  const owner = repository.owner.login;
  const repoName = repository.name;
  const repoFullName = repository.full_name;

  console.log(
    `[review] Processing PR #${pr.number} in ${repoFullName} (action: ${action})`,
  );

  const octokit = createOctokit();
  const diff = await fetchPullRequestDiff(octokit, owner, repoName, pr.number);

  if (!diff || diff.trim().length === 0) {
    console.warn(`[review] PR #${pr.number} in ${repoFullName} has an empty diff, skipping.`);
    return;
  }

  const { review, rawResponseText } = await reviewDiff({
    repo: repoFullName,
    prNumber: pr.number,
    prTitle: pr.title,
    diff,
  });

  const pullRequestId = await upsertPullRequest({
    repo: repoFullName,
    prNumber: pr.number,
    prTitle: pr.title,
    prUrl: pr.html_url,
    diffSummary: review.summary,
  });

  const reviewId = await insertReview({
    pullRequestId,
    review,
    rawResponse: rawResponseText,
  });

  try {
    await postPullRequestComment(
      octokit,
      owner,
      repoName,
      pr.number,
      formatReviewComment(review),
    );
  } catch (err) {
    // The review is already saved and visible on the dashboard even if
    // posting the GitHub comment fails (e.g. token lacks write access).
    console.error(
      `[review] Saved review #${reviewId} but failed to post PR comment:`,
      err,
    );
  }

  console.log(
    `[review] Done: PR #${pr.number} risk=${review.risk_level} verdict=${review.verdict} (review id ${reviewId})`,
  );
}

function riskBadge(risk: string): string {
  switch (risk) {
    case "low":
      return "🟢 Low";
    case "medium":
      return "🟡 Medium";
    case "high":
      return "🔴 High";
    default:
      return risk;
  }
}

function formatReviewComment(review: ReviewResult): string {
  const lines: string[] = [];

  lines.push("### 🤖 AI PR Review");
  lines.push("");
  lines.push(`**Risk level:** ${riskBadge(review.risk_level)}  |  **Verdict:** \`${review.verdict}\``);
  lines.push("");
  lines.push("**Summary**");
  lines.push(review.summary);

  if (review.risks.length > 0) {
    lines.push("");
    lines.push("**Risks & concerns**");
    for (const risk of review.risks) lines.push(`- ${risk}`);
  }

  if (review.missing_tests.length > 0) {
    lines.push("");
    lines.push("**Possible missing test coverage**");
    for (const item of review.missing_tests) lines.push(`- ${item}`);
  }

  lines.push("");
  lines.push("_Automated review generated by ai-pr-reviewer, powered by Claude. Use judgment — this does not replace a human review._");

  return lines.join("\n");
}
